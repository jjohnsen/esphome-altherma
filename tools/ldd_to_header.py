#!/usr/bin/env python3
"""Convert decoded Daikin D-Checker LDD rows to an ESPHome C++ sensor profile.

An .ldd is decoded offline using tools/ldd_decode.py. ESP32 firmware does not
parse .ldd/.csv at runtime: only native ESPHome entities are registered at boot.
"""

import argparse
import csv
import json
import re
from collections import Counter
from pathlib import Path

# Deliberately small, proven numeric subset of the vendored ESPAltherma
# converters.h. Expand only after validating byte order, types and units.
SUPPORTED_CONVERTERS = {101, 105, 151, 152}
SAFE_LABEL = re.compile(r"[\x20-\x7e\u00a0-\uffff]")
DISPLAY_DECIMALS = re.compile(r"^%\.(\d+)f$")


def bool_field(value):
    return str(value).strip().lower() in {"true", "1", "yes"}


def load_rows(path):
    if path.suffix.lower() == ".ldd":
        from ldd_decode import decode
        rows, _ = decode(path)
        if not isinstance(rows, list):
            raise ValueError("LDD did not decode to a row list")
        return rows
    if path.suffix.lower() == ".csv":
        with path.open(encoding="utf-8-sig", newline="") as stream:
            return list(csv.DictReader(line for line in stream
                                       if line.strip() and not line.lstrip().startswith("#")))
    raise ValueError("Expected a .ldd or decoded .csv file")


def make_definitions(rows, *, limit):
    definitions = []
    rejected = Counter()
    names = set()
    for row in rows:
        if not isinstance(row, dict):
            rejected["invalid row"] += 1
            continue
        address = str(row.get("DataId", "")).strip()
        # Wildcard entries (e.g. '0x3*') require hardware-aware resolution.
        if not re.fullmatch(r"0[xX][0-9a-fA-F]{2}", address):
            rejected["wildcard/invalid register"] += 1
            continue
        if not bool_field(row.get("Enabled")) or not bool_field(row.get("IsDisplay")):
            rejected["hidden/disabled"] += 1
            continue
        label = str(row.get("LabelStr") or "").strip()
        if not label or label.lower() in {"not in use", "nextdatagrid"}:
            rejected["missing/placeholder label"] += 1
            continue
        if "override" in label.lower() or "command" in label.lower():
            rejected["control/command field"] += 1
            continue
        try:
            reg = int(address, 16)
            offset = int(row.get("Offset"))
            size = int(row.get("Bytes"))
            convid = int(row.get("ConvId"))
        except (TypeError, ValueError):
            rejected["invalid numeric fields"] += 1
            continue
        if convid not in SUPPORTED_CONVERTERS:
            rejected["unsupported converter"] += 1
            continue
        if size not in (1, 2, 4) or offset < 0 or offset + size > 60:
            rejected["unsafe byte bounds"] += 1
            continue
        # We cannot safely expose these fields until they are validated as read-only.
        if str(row.get("DataKind", "")).strip().upper() == "W":
            rejected["write field"] += 1
            continue
        label = "".join(c if SAFE_LABEL.fullmatch(c) else " " for c in label)
        label = " ".join(label.split())
        name = f"LDD {label}"
        if name in names:
            name += f" (0x{reg:02X}:{offset}:{convid})"
        if name in names:
            rejected["duplicate name"] += 1
            continue
        names.add(name)
        format_match = DISPLAY_DECIMALS.fullmatch(str(row.get("FormatStr", "")))
        decimals = min(int(format_match.group(1)), 3) if format_match else 0
        definitions.append((name, reg, offset, size, convid, decimals))
        if len(definitions) > limit:
            raise ValueError(f"More than {limit} sensors; choose a smaller LDD profile")
    return definitions, rejected


def render_header(definitions, source_name):
    def literal(text):
        return json.dumps(text, ensure_ascii=False)

    lines = [
        "// Generated by tools/ldd_to_header.py -- DO NOT EDIT BY HAND.",
        f"// Source: {Path(source_name).name} (offline conversion, read-only values)",
        "#pragma once",
        "#include <cstdint>",
        "#include <cstddef>",
        "namespace esphome { namespace altherma_hub {",
        "struct LddSensorDefinition {",
        "  const char *name;",
        "  uint8_t register_id;",
        "  uint8_t offset;",
        "  uint8_t data_size;",
        "  uint16_t converter_id;",
        "  uint8_t decimals;",
        "};",
        "static constexpr LddSensorDefinition LDD_SENSOR_DEFINITIONS[] = {",
    ]
    for name, reg, offset, size, convid, decimals in definitions:
        lines.append(f"  {{{literal(name)}, 0x{reg:02X}, {offset}, {size}, {convid}, {decimals}}},")
    lines.extend([
        "};",
        "static constexpr size_t LDD_SENSOR_COUNT = sizeof(LDD_SENSOR_DEFINITIONS) / sizeof(LDD_SENSOR_DEFINITIONS[0]);",
        "} }  // namespace esphome::altherma_hub",
        "",
    ])
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("input", type=Path, help="Daikin .ldd or decoded CSV input")
    p.add_argument("--output", type=Path, default=Path("components/altherma_hub/ldd_generated_profile.h"))
    p.add_argument("--max-sensors", type=int, default=64)
    args = p.parse_args()
    if not 1 <= args.max_sensors <= 256:
        p.error("--max-sensors must be between 1 and 256")
    definitions, rejected = make_definitions(load_rows(args.input), limit=args.max_sensors)
    if not definitions:
        p.error("No safe supported numeric sensor definitions in input")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_header(definitions, args.input.name), encoding="utf-8")
    print(f"Generated {len(definitions)} sensors: {args.output}")
    for why, count in rejected.most_common():
        print(f"  skipped {count}: {why}")


if __name__ == "__main__":
    main()
